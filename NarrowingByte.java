class NarrowingByte
	{
		public static void main(String[] args)
			{
			   short a=130;
			   int b=130;
			   long c=130l;
			   char d='a';
			   float e=130.2f;
			   double f=130.2;
			   byte b1=(byte)a;
			   byte b2=(byte)b;
			   byte b3=(byte)c;
			   byte b4=(byte)d;
			    byte b5=(byte)e;
			     byte b6=(byte)f;
			
			System.out.println(b1);
		        System.out.println(b2);
			System.out.println(b3);
			System.out.println(b4);
			System.out.println(b5);
			System.out.println(b6);	
			
			
			}
	}

