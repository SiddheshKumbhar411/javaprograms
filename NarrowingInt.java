class NarrowingInt
	{
		public static void main(String[] args)
			{
			   
			   
			   long c=330000l;
			   char d='z';
			   float e=130.2f;
			   double f=130.2;
			   int b1=(int)c;
			   int b2=(int)d;
			   int  b3=(int)e;
			   int b4=(int)f;
			    
			  System.out.println(b1);
		        System.out.println(b2);
			System.out.println(b3);
			System.out.println(b4);
						
			
			
			}
	}

