class NarrowingChar
	{
		public static void main(String[] args)
			{
			   
			   int b=97;
			   long c=97l;
			 
			   float e=97.0f;
			   double f=97.0;
			   char b1=(char)b;
			   char b2=(char)c;
			   char b3=(char)e;
			    char b4=(char)f;
			  System.out.println(b1);
		        System.out.println(b2);
			System.out.println(b3);
			System.out.println(b4);
						
			
			}
	}

